-- Durable billing queue maintenance.  Vault secrets are deliberately read at
-- execution time; none are committed to the repository.

create extension if not exists pg_cron;
create extension if not exists pg_net;

select cron.schedule(
  'invoke-process-billing-webhooks',
  '*/5 * * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name = 'project_url') || '/functions/v1/process-billing-webhooks',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'cron_secret')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 60000
  );
  $$
);

