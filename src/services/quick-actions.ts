import { Platform } from 'react-native';

import type { NewMemoryAction } from '@/lib/routes';

/**
 * Home-screen app shortcuts (iOS Home Screen Quick Actions / Android app
 * shortcuts). See docs/features/app-shortcuts.md.
 */
export type QuickActionsModule = typeof import('expo-quick-actions');

let loadedModule: QuickActionsModule | null | undefined;

/**
 * expo-quick-actions reads its native module at import time. A binary built
 * before it was added (for example an OTA update running on an older build)
 * must keep working without shortcuts rather than crash, so load it lazily
 * and treat any failure as "not available".
 */
export function getQuickActionsModule(): QuickActionsModule | null {
  if (Platform.OS === 'web') return null;
  if (loadedModule !== undefined) return loadedModule;
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    loadedModule = require('expo-quick-actions') as QuickActionsModule;
  } catch {
    loadedModule = null;
  }
  return loadedModule;
}

/** Test-only: forget the cached module lookup. */
export function resetQuickActionsModuleForTests(): void {
  loadedModule = undefined;
}

interface ShortcutDefinition {
  id: string;
  action: NewMemoryAction;
  title: string;
  /** SF Symbol name (iOS only). */
  symbol: string;
  /** Android adaptive icon generated by the expo-quick-actions plugin (`androidIcons` in app.json). */
  androidIcon: string;
}

// Order is the order shown in the long-press menu. To add a shortcut, extend
// NEW_MEMORY_ACTIONS in src/lib/routes.ts and add an entry here.
export const SHORTCUTS: readonly ShortcutDefinition[] = [
  { id: 'new-memory', action: 'text', title: 'New memory', symbol: 'square.and.pencil', androidIcon: 'shortcut_compose' },
  { id: 'take-photo', action: 'photo', title: 'Take a photo', symbol: 'camera', androidIcon: 'shortcut_camera' },
  { id: 'record-audio', action: 'voice', title: 'Record audio', symbol: 'mic', androidIcon: 'shortcut_mic' },
  { id: 'scan-artwork', action: 'scan', title: 'Scan artwork', symbol: 'doc.viewfinder', androidIcon: 'shortcut_scan' },
];

/** Maps a triggered shortcut (by id) back to the composer action; unknown ids are ignored. */
export function actionForShortcutId(id: unknown): NewMemoryAction | undefined {
  return SHORTCUTS.find((shortcut) => shortcut.id === id)?.action;
}

/**
 * Publishes the shortcuts, or clears them (`enabled: false`). Best-effort:
 * a missing native module or a platform error just means no shortcuts.
 */
export async function setQuickActionsEnabled(enabled: boolean): Promise<void> {
  const module = getQuickActionsModule();
  if (!module) return;
  try {
    await module.setItems(
      enabled
        ? SHORTCUTS.map((shortcut) => ({
            id: shortcut.id,
            title: shortcut.title,
            icon: Platform.OS === 'ios' ? `symbol:${shortcut.symbol}` : shortcut.androidIcon,
          }))
        : [],
    );
  } catch {
    // Shortcuts are a convenience; never disrupt the app over them.
  }
}

let initialDelivered = false;

/** Test-only: allow the launch shortcut to be delivered again. */
export function resetQuickActionLaunchForTests(): void {
  initialDelivered = false;
}

/**
 * Subscribes to shortcut launches: the one that cold-started the app (once
 * per process, even if the subscriber remounts) and later ones while the app
 * is running or resumed from the background. Returns an unsubscribe function;
 * a no-op when the native module is missing.
 */
export function subscribeToQuickActions(listener: (action: NewMemoryAction) => void): () => void {
  const module = getQuickActionsModule();
  if (!module) return () => {};

  if (!initialDelivered) {
    initialDelivered = true;
    const initial = actionForShortcutId(module.initial?.id);
    if (initial) listener(initial);
  }

  try {
    const subscription = module.addListener((payload) => {
      const action = actionForShortcutId(payload?.id);
      if (action) listener(action);
    });
    return () => subscription.remove();
  } catch {
    return () => {};
  }
}
